let a = parseFloat(prompt("Ingresar el primer valor:"));
let b = parseFloat(prompt("Ingresar el segundo valor:"));
let c = parseFloat(prompt("Ingresar el tercer valor:"));

let mayor = Math.max(a, b, c);
let menor = Math.min(a, b, c);

console.log("El mayor es: " + mayor);
console.log("El menor es: " + menor);
